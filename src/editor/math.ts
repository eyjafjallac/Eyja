import {
  snippetCompletion,
  type Completion,
  type CompletionSection,
} from "@codemirror/autocomplete";

const structure: CompletionSection = { name: "Structure", rank: 0 };
const greek: CompletionSection = { name: "Greek", rank: 1 };
const operator: CompletionSection = { name: "Operator", rank: 2 };
const arrow: CompletionSection = { name: "Arrow", rank: 3 };
const fn: CompletionSection = { name: "Function", rank: 4 };

function command(
  name: string,
  detail: string,
  section: CompletionSection,
  template?: string,
  boost = 0,
): Completion {
  const completion: Completion = {
    label: `\\${name}`,
    detail,
    section,
    boost,
  };
  return template ? snippetCompletion(template, completion) : completion;
}

